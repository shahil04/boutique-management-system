CREATE TABLE IF NOT EXISTS customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  phone text NOT NULL,
  phone_key text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint REFERENCES customers(id) ON DELETE SET NULL,
  serial_no text NOT NULL,
  customer_name text NOT NULL,
  phone text NOT NULL,
  address text NOT NULL DEFAULT '',
  garment_type text NOT NULL DEFAULT '',
  order_date text NOT NULL,
  delivery_date text NOT NULL,
  status text NOT NULL DEFAULT 'Received',
  measurements_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  items_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  total_amount numeric NOT NULL DEFAULT 0,
  advance_paid numeric NOT NULL DEFAULT 0,
  balance_due numeric NOT NULL DEFAULT 0,
  slip_photo_url text NOT NULL DEFAULT '',
  design_photos_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  ocr_raw_json text NOT NULL DEFAULT '',
  ocr_confidence text NOT NULL DEFAULT 'none',
  verified_by text NOT NULL DEFAULT '',
  created_at text NOT NULL,
  updated_at text NOT NULL
);

CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value text NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_orders_serial_no ON orders(serial_no);
CREATE INDEX IF NOT EXISTS idx_orders_phone ON orders(phone);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_delivery_date ON orders(delivery_date);
CREATE INDEX IF NOT EXISTS idx_orders_customer_id ON orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_customers_phone_key ON customers(phone_key);

